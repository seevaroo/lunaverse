-- ============================================================
-- PROFIL DAN ROLE PENGGUNA
-- ============================================================

create table public.profil_pengguna (
  id uuid primary key references auth.users(id) on delete cascade,
  email text not null unique,
  nama text not null default 'Learner',
  role text not null default 'user' check (role in ('admin', 'user')),
  dibuat_pada timestamptz not null default now(),
  diperbarui_pada timestamptz not null default now()
);

create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer set search_path = public
as $$
begin
  insert into public.profil_pengguna (id, email, nama, role)
  values (
    new.id,
    new.email,
    coalesce(new.raw_user_meta_data ->> 'name', 'Learner'),
    coalesce(new.raw_user_meta_data ->> 'role', 'user')
  )
  on conflict (id) do update set
    email = excluded.email,
    nama = excluded.nama;
  return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
after insert on auth.users
for each row execute function public.handle_new_user();

-- Pulihkan profil untuk akun Auth yang sudah ada sebelum schema ini dijalankan.
insert into public.profil_pengguna (id, email, nama, role)
select
  id,
  email,
  coalesce(raw_user_meta_data ->> 'name', 'Learner'),
  coalesce(raw_user_meta_data ->> 'role', 'user')
from auth.users
where email is not null
on conflict (id) do update set
  email = excluded.email,
  nama = excluded.nama;

create or replace function public.is_admin()
returns boolean
language sql
stable
security definer set search_path = public
as $$
  select exists (
    select 1 from public.profil_pengguna
    where id = auth.uid() and role = 'admin'
  );
$$;

-- ============================================================
-- BAHASA
-- ============================================================

create table public.languages (
  id text primary key,
  name text not null,
  native_name text not null,
  icon text not null default '🌐',
  lesson_count integer not null default 0 check (lesson_count >= 0),
  created_at timestamptz not null default now()
);

-- ============================================================
-- MATERI
-- ============================================================

create table public.lessons (
  id bigint generated by default as identity primary key,
  language_id text not null references public.languages(id) on delete cascade,
  title text not null,
  summary text not null default '',
  content text not null default '',
  created_at timestamptz not null default now()
);

create index lessons_language_id_idx on public.lessons(language_id);

-- ============================================================
-- BANK SOAL
-- ============================================================

create table public.quiz_questions (
  id bigint generated by default as identity primary key,
  language_id text not null references public.languages(id) on delete cascade,
  question text not null,
  options text[] not null check (cardinality(options) >= 2),
  answer_index integer not null check (answer_index >= 0 and answer_index < cardinality(options)),
  created_at timestamptz not null default now()
);

create index quiz_questions_language_id_idx on public.quiz_questions(language_id);

-- ============================================================
-- HASIL QUIZ
-- ============================================================

create table public.quiz_attempts (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  language text not null,
  score integer not null check (score between 0 and 100),
  created_at timestamptz not null default now()
);

create index quiz_attempts_user_id_idx on public.quiz_attempts(user_id);

-- STREAK BELAJAR HARIAN
create table public.user_streaks (
  user_id uuid primary key references auth.users(id) on delete cascade,
  streak_count integer not null default 0 check (streak_count >= 0),
  last_activity_date date,
  updated_at timestamptz not null default now()
);

alter table public.user_streaks enable row level security;
create policy "streak_self_select" on public.user_streaks
for select to authenticated using (user_id = auth.uid());
create policy "streak_self_write" on public.user_streaks
for insert to authenticated with check (user_id = auth.uid());
create policy "streak_self_update" on public.user_streaks
for update to authenticated using (user_id = auth.uid()) with check (user_id = auth.uid());

-- ============================================================
-- SERTIFIKAT
-- ============================================================

create table public.certificates (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  title text not null,
  issued_at timestamptz not null default now()
);

create index certificates_user_id_idx on public.certificates(user_id);

