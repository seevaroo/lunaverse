-- ============================================================
-- RLS DAN POLICY
-- ============================================================

alter table public.profil_pengguna enable row level security;
alter table public.languages enable row level security;
alter table public.lessons enable row level security;
alter table public.quiz_questions enable row level security;
alter table public.quiz_attempts enable row level security;
alter table public.certificates enable row level security;

create policy "profile_self_select" on public.profil_pengguna
for select to authenticated using (id = auth.uid() or public.is_admin());

create policy "profile_admin_write" on public.profil_pengguna
for all to authenticated using (public.is_admin()) with check (public.is_admin());

create policy "languages_authenticated_select" on public.languages
for select to authenticated using (true);

create policy "languages_admin_write" on public.languages
for all to authenticated using (public.is_admin()) with check (public.is_admin());

create policy "lessons_authenticated_select" on public.lessons
for select to authenticated using (true);

create policy "lessons_admin_write" on public.lessons
for all to authenticated using (public.is_admin()) with check (public.is_admin());

create policy "questions_authenticated_select" on public.quiz_questions
for select to authenticated using (true);

create policy "questions_admin_write" on public.quiz_questions
for all to authenticated using (public.is_admin()) with check (public.is_admin());

create policy "attempts_self_select" on public.quiz_attempts
for select to authenticated using (user_id = auth.uid() or public.is_admin());

create policy "attempts_self_insert" on public.quiz_attempts
for insert to authenticated with check (user_id = auth.uid());

create policy "attempts_admin_write" on public.quiz_attempts
for update to authenticated using (public.is_admin()) with check (public.is_admin());

create policy "attempts_admin_delete" on public.quiz_attempts
for delete to authenticated using (public.is_admin());

create policy "certificates_self_select" on public.certificates
for select to authenticated using (user_id = auth.uid() or public.is_admin());

create policy "certificates_admin_write" on public.certificates
for all to authenticated using (public.is_admin()) with check (public.is_admin());

